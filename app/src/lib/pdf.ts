import { jsPDF } from 'jspdf'
import type { DGCAEntitlement } from '../types'

export function generateGrievancePDF(flightNumber: string, entitlements: DGCAEntitlement[]) {
  const doc = new jsPDF()

  doc.setFillColor(15, 23, 42)
  doc.rect(0, 0, 210, 40, 'F')
  doc.setTextColor(255, 255, 255)
  doc.setFontSize(18)
  doc.setFont('helvetica', 'bold')
  doc.text('OpenGagan — DGCA Passenger Rights', 20, 18)
  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.text('Grievance Document under CAR Section 3 Series M Part IV', 20, 28)

  doc.setTextColor(15, 23, 42)
  doc.setFontSize(12)
  doc.setFont('helvetica', 'bold')
  doc.text('Flight Details', 20, 55)
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  doc.text(`Flight Number: ${flightNumber || 'Not specified'}`, 20, 65)
  doc.text(`Date Generated: ${new Date().toLocaleDateString('en-IN', { dateStyle: 'long' })}`, 20, 73)

  doc.setFontSize(12)
  doc.setFont('helvetica', 'bold')
  doc.text('Your Entitlements', 20, 90)

  let y = 100
  entitlements.forEach((e, i) => {
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(10)
    doc.setTextColor(15, 118, 110)
    doc.text(`${i + 1}. ${e.label}`, 20, y)
    y += 8

    if (e.amount) {
      doc.setTextColor(15, 23, 42)
      doc.setFont('helvetica', 'normal')
      doc.text(`   Compensation: ₹${e.amount.toLocaleString('en-IN')}`, 20, y)
      y += 7
    }

    if (e.rule) {
      doc.setTextColor(100, 116, 139)
      doc.setFontSize(8)
      doc.text(`   Rule: ${e.rule}`, 20, y)
      y += 7
    }

    doc.setTextColor(15, 23, 42)
    doc.setFontSize(10)
    y += 3
  })

  y = Math.max(y + 10, 220)
  doc.setDrawColor(226, 232, 240)
  doc.line(20, y, 190, y)
  y += 8
  doc.setFontSize(9)
  doc.setTextColor(100, 116, 139)
  doc.text('File your grievance at: https://airsewa.gov.in', 20, y)
  y += 7
  doc.text('DGCA Helpline: 1800-11-1118 (toll-free)', 20, y)
  y += 7
  doc.text('Generated by OpenGagan — Open Source Aviation Equity Map', 20, y)
  y += 7
  doc.text('https://github.com/dhanvanthshetty/opengagan', 20, y)

  doc.save(`dgca-grievance-${flightNumber || 'unknown'}-${Date.now()}.pdf`)
}
